"""Builds lib/widgets/app_icons.g.dart from the design kit's 24px line icons.

Duotone (the chosen style): every icon keeps its rounded 2px lines in the icon
colour, and its main shape (the first rect / circle, or a closed path) gets a soft
fill of the same colour. Usage:

    python tool/make_icons.py <kit>/icons
"""

import re
import sys
from pathlib import Path

# Two kit icons read badly; redrawn here.
OVERRIDES = {
    # A card moving right, not a "log out" arrow.
    "swipe_applied": '<rect x="3" y="6" width="11" height="12" rx="3" /><path d="M17 12h5m-2.5-3 2.5 3-2.5 3" />',
    # A plain cloud with a tick.
    "backup_done": '<path d="M7 18h10a4 4 0 0 0 .6-7.95A6 6 0 0 0 6.2 9.4 4.4 4.4 0 0 0 7 18z" /><path d="m9.5 13.6 2 2 3.6-3.7" />',
}

# Icons the kit doesn't have.
EXTRAS = {
    # A stopwatch with a tick: timed practice tests.
    "practice": '<circle cx="12" cy="13" r="8" /><path d="M10 2h4M12 2v3m6.5 1.5L20 5M9 13l2 2 4-4" />',
}

FILL = ' fill="currentColor" fill-opacity="0.22"'


def duotone(inner: str) -> str:
    """Soft fill on the main shape: the first rect/circle, else the first closed path."""
    for tag in ("rect", "circle"):
        m = re.search(rf"<{tag}\b(?![^>]*\bfill=)", inner)
        if m:
            return inner[: m.end()] + FILL + inner[m.end():]
    for m in re.finditer(r"<path\b([^>]*)/?>", inner):
        if re.search(r'd="[^"]*[zZ]', m.group(0)) and "fill=" not in m.group(0):
            return inner[: m.start() + 5] + FILL + inner[m.start() + 5:]
    return inner


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w.capitalize() for w in rest)


def main(kit: Path) -> None:
    entries = []
    for svg in sorted(kit.glob("*.svg")):
        text = svg.read_text(encoding="utf-8")
        inner = OVERRIDES.get(svg.stem) or re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1).strip()
        inner = " ".join(duotone(inner).split())
        entries.append((camel(svg.stem), inner))
    for name, inner in EXTRAS.items():
        entries.append((camel(name), " ".join(duotone(inner).split())))
    entries.sort()
    out = Path(__file__).resolve().parents[1] / "lib" / "widgets" / "app_icons.g.dart"
    lines = [
        "// GENERATED by tool/make_icons.py from the design kit. Do not edit by hand.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "part of 'app_icons.dart';",
        "",
        "enum AppIcon {",
        *[f"  {name}," for name, _ in entries],
        "}",
        "",
        "const _svgHead =",
        "    '<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" '",
        "    'stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\">';",
        "",
        "const _bodies = <AppIcon, String>{",
        *[f"  AppIcon.{name}: '{body}'," for name, body in entries],
        "};",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(entries)} icons -> {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
